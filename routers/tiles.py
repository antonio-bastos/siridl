"""FastAPI router serving PostGIS Mapbox Vector Tiles (ST_AsMVT) from Supabase PostgreSQL."""

from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, HTTPException, Response

from services.supabase_db import get_database_url

try:
    import psycopg
except ImportError:  # pragma: no cover
    psycopg = None


router = APIRouter(prefix="/api/v1/tiles", tags=["tiles"])

MVT_MEDIA_TYPE = "application/vnd.mapbox-vector-tile"


def query_anomalies_mvt(z: int, x: int, y: int) -> tuple[Optional[bytes], str]:
    """Query PostGIS ST_AsMVT on public.road_anomalies for tile (z, x, y)."""
    database_url = get_database_url()
    if not database_url or psycopg is None:
        return None, "offline-fallback"

    sql = """
        WITH bounds AS (
            SELECT ST_TileEnvelope(%(z)s, %(x)s, %(y)s) AS geom
        ),
        mvtgeom AS (
            SELECT
                ra.id::text AS id,
                ra.anomaly_code,
                ra.anomaly_type,
                ra.severity,
                COALESCE(ra.street_name, 'Via Municipal (Loulé)') AS street_name,
                COALESCE(ra.parish, 'Loulé') AS parish,
                COALESCE(ra.gestao, 'Câmara Municipal de Loulé') AS gestao,
                ROUND(COALESCE(ra.confidence, 0.0)::numeric, 4) AS confidence,
                ROUND(COALESCE(ra.estimated_area_cm2, 0.0)::numeric, 1) AS estimated_area_cm2,
                ST_AsMVTGeom(
                    ST_Transform(ra.geom::geometry, 3857),
                    bounds.geom,
                    4096,
                    256,
                    true
                ) AS geom
            FROM public.road_anomalies AS ra, bounds
            WHERE ra.deleted_at IS NULL
              AND ra.geom IS NOT NULL
              AND ST_Intersects(ST_Transform(ra.geom::geometry, 3857), bounds.geom)
        )
        SELECT ST_AsMVT(mvtgeom.*, 'anomalies', 4096, 'geom') AS mvt
        FROM mvtgeom;
    """
    try:
        with psycopg.connect(database_url, sslmode="require") as conn:
            with conn.cursor() as cur:
                cur.execute(sql, {"z": z, "x": x, "y": y})
                row = cur.fetchone()
                mvt_raw = bytes(row[0]) if row and row[0] else b""
                return mvt_raw, "supabase-postgis-st-asmvt"
    except Exception:
        return None, "postgis-error-fallback"


@router.get("/anomalies/{z}/{x}/{y}.pbf")
async def get_anomalies_vector_tile(z: int, x: int, y: int) -> Response:
    """Serve dynamic Mapbox Vector Tiles (.pbf) generated by Supabase PostGIS ST_AsMVT()."""
    if not (0 <= z <= 22):
        raise HTTPException(status_code=400, detail="Nível de zoom inválido.")
    max_coord = 1 << z
    if not (0 <= x < max_coord and 0 <= y < max_coord):
        raise HTTPException(status_code=400, detail="Coordenadas de mosaico inválidas.")

    mvt_bytes, source_mode = query_anomalies_mvt(z, x, y)
    if not mvt_bytes:
        return Response(
            status_code=204,
            headers={
                "Cache-Control": "public, max-age=15",
                "X-Tile-Source": source_mode,
            },
        )

    return Response(
        content=mvt_bytes,
        media_type=MVT_MEDIA_TYPE,
        headers={
            "Cache-Control": "public, max-age=15",
            "X-Tile-Source": source_mode,
        },
    )
